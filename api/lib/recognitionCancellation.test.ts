import { describe, expect, it } from "vitest";
import {
  canCancelFlowRecognition,
  chunkRecognitionCancellationDetailIds,
  classifyRecognitionCancellationDetailCoverage,
  deriveDetailOperationCancellationDecision,
  deriveDetailOperationOriginalTaskId,
  deriveFlowRecognitionCancellationScope,
  getRecognitionResultKind,
  hasArchivedRecognitionDetails,
  mergeFlowRecognitionCancellationScopes,
  partitionRecognitionResultIds,
  retryCommittedRecognitionCancellationRefresh,
  selectRecognitionResultGroup,
  type RecognitionResultGroupRow,
} from "./recognitionCancellation";

function row(patch: Partial<RecognitionResultGroupRow>): RecognitionResultGroupRow {
  return {
    id: 1,
    taskId: 10,
    bankFlowId: 20,
    ruleItemId: null,
    incomeRuleId: null,
    totalAmount: "100.00",
    splitAmount: "100.00",
    detailCount: 0,
    orderDetailCountSnapshot: 0,
    incomeType: "捐赠收入",
    entryTime: "2026-07-10",
    ...patch,
  };
}

describe("recognition cancellation grouping", () => {
  it("groups every split generated by one income recognition", () => {
    const selected = row({ id: 2, incomeRuleId: 8, splitAmount: "40.00" });
    const rows = [
      row({ id: 1, incomeRuleId: 8, splitAmount: "60.00" }),
      selected,
      row({ id: 3, bankFlowId: 21, incomeRuleId: 8 }),
    ];
    expect(getRecognitionResultKind(selected)).toBe("income");
    expect(selectRecognitionResultGroup(rows, selected).map((item) => item.id)).toEqual([1, 2]);
  });

  it("uses the positive detail-count row as a detail split boundary", () => {
    const selected = row({ id: 2, ruleItemId: 9, detailCount: 0, orderDetailCountSnapshot: 3, splitAmount: "40.00" });
    const rows = [
      row({ id: 1, ruleItemId: 9, detailCount: 3, orderDetailCountSnapshot: 3, splitAmount: "60.00" }),
      selected,
      row({ id: 3, ruleItemId: 9, detailCount: 2, orderDetailCountSnapshot: 3, splitAmount: "100.00" }),
    ];
    expect(getRecognitionResultKind(selected)).toBe("detail");
    expect(selectRecognitionResultGroup(rows, selected).map((item) => item.id)).toEqual([1, 2]);
  });

  it("keeps identical manual recognition operations in separate amount groups", () => {
    const selected = row({ id: 4, splitAmount: "30.00" });
    const rows = [
      row({ id: 1, splitAmount: "60.00" }),
      row({ id: 2, splitAmount: "40.00" }),
      row({ id: 3, splitAmount: "70.00" }),
      selected,
    ];
    expect(getRecognitionResultKind(selected)).toBe("manual_flow");
    expect(selectRecognitionResultGroup(rows, selected).map((item) => item.id)).toEqual([3, 4]);
  });

  it("groups all split rows for one manual detail recognition", () => {
    const selected = row({ id: 6, detailCount: 0, orderDetailCountSnapshot: 1, splitAmount: "25.00", incomeType: "其他收入" });
    const rows = [
      row({ id: 5, detailCount: 1, orderDetailCountSnapshot: 1, splitAmount: "75.00" }),
      selected,
      row({ id: 7, detailCount: 1, orderDetailCountSnapshot: 1, splitAmount: "100.00" }),
    ];
    expect(getRecognitionResultKind(selected)).toBe("manual_detail");
    expect(selectRecognitionResultGroup(rows, selected).map((item) => item.id)).toEqual([5, 6]);
  });

  it("classifies every recognition kind for a whole-flow rollback", () => {
    const partitions = partitionRecognitionResultIds([
      row({ id: 1, incomeRuleId: 8 }),
      row({ id: 2, ruleItemId: 9, orderDetailCountSnapshot: 3 }),
      row({ id: 3, orderDetailCountSnapshot: 1 }),
      row({ id: 4 }),
    ]);

    expect(partitions).toEqual({
      income: [1],
      detail: [2],
      manual_detail: [3],
      manual_flow: [4],
    });
  });
});

describe("flow recognition cancellation scope", () => {
  it("keeps an ordinary arrival scoped to the clicked flow", () => {
    expect(deriveFlowRecognitionCancellationScope({
      clickedFlow: { id: 20, taskId: 10 },
      taskFlowCount: 2,
    })).toEqual({
      type: "flow",
      flowIds: [20],
      taskIds: [10],
      includeTaskScopedLegacyResults: false,
    });
  });

  it("includes task-scoped legacy results when the ordinary task has one flow", () => {
    expect(deriveFlowRecognitionCancellationScope({
      clickedFlow: { id: 20, taskId: 10 },
      taskFlowCount: 1,
    }).includeTaskScopedLegacyResults).toBe(true);
  });

  it("uses the complete same-day aggregate task from any included flow", () => {
    expect(deriveFlowRecognitionCancellationScope({
      clickedFlow: { id: 21, taskId: 10 },
      aggregateFlows: [
        { id: 20, taskId: 10 },
        { id: 21, taskId: 10 },
        { id: 22, taskId: 10 },
      ],
      taskFlowCount: 3,
    })).toEqual({
      type: "same_day",
      flowIds: [20, 21, 22],
      taskIds: [10],
      includeTaskScopedLegacyResults: true,
    });
  });

  it("uses only the confirmed multi-day match group and all related tasks", () => {
    expect(deriveFlowRecognitionCancellationScope({
      clickedFlow: { id: 31, taskId: 11 },
      aggregateFlows: [
        { id: 30, taskId: 10 },
        { id: 31, taskId: 11 },
        { id: 32, taskId: 12 },
      ],
      isMultiDay: true,
      taskFlowCount: 1,
    })).toEqual({
      type: "multi_day",
      flowIds: [30, 31, 32],
      taskIds: [10, 11, 12],
      includeTaskScopedLegacyResults: false,
    });
  });

  it("falls back to the clicked flow when an aggregate context does not contain it", () => {
    expect(deriveFlowRecognitionCancellationScope({
      clickedFlow: { id: 40, taskId: 13 },
      aggregateFlows: [
        { id: 30, taskId: 10 },
        { id: 31, taskId: 11 },
      ],
      isMultiDay: true,
      taskFlowCount: 2,
    })).toEqual({
      type: "flow",
      flowIds: [40],
      taskIds: [13],
      includeTaskScopedLegacyResults: false,
    });
  });
});

describe("detail operation recognition cancellation", () => {
  it("uses the current task for ignored details and the original task for transferred details", () => {
    expect(deriveDetailOperationOriginalTaskId({
      operationStatus: "ignored",
      taskId: 10,
      originalTaskId: null,
    })).toBe(10);
    expect(deriveDetailOperationOriginalTaskId({
      operationStatus: "transferred",
      taskId: 20,
      originalTaskId: 10,
    })).toBe(10);
    expect(deriveDetailOperationOriginalTaskId({
      operationStatus: "active",
      taskId: 10,
      originalTaskId: null,
    })).toBe(0);
  });

  it("deduplicates aggregate scopes and combines separate ordinary flows", () => {
    expect(mergeFlowRecognitionCancellationScopes([
      {
        type: "same_day",
        flowIds: [21, 20],
        taskIds: [10],
        includeTaskScopedLegacyResults: true,
      },
      {
        type: "same_day",
        flowIds: [20, 21],
        taskIds: [10],
        includeTaskScopedLegacyResults: true,
      },
    ])).toEqual({
      type: "same_day",
      flowIds: [20, 21],
      taskIds: [10],
      scopeCount: 1,
    });

    expect(mergeFlowRecognitionCancellationScopes([
      {
        type: "flow",
        flowIds: [30],
        taskIds: [11],
        includeTaskScopedLegacyResults: false,
      },
      {
        type: "flow",
        flowIds: [31],
        taskIds: [11],
        includeTaskScopedLegacyResults: false,
      },
    ])).toEqual({
      type: "multiple",
      flowIds: [30, 31],
      taskIds: [11],
      scopeCount: 2,
    });
  });

  it("only asks for confirmation when the original task has cancellable recognition results", () => {
    expect(deriveDetailOperationCancellationDecision({
      resultCount: 0,
      hasCancelPermission: false,
      hasLockedResult: false,
      hasGeneratedVoucher: false,
      operationLabel: "忽略",
      originalDate: "2026-07-24",
      scopeLabel: "该银行到账",
    })).toEqual({
      requiresConfirmation: false,
      canContinue: true,
      message: "",
    });

    expect(deriveDetailOperationCancellationDecision({
      resultCount: 3,
      hasCancelPermission: true,
      hasLockedResult: false,
      hasGeneratedVoucher: false,
      operationLabel: "转移",
      originalDate: "2026-07-24",
      scopeLabel: "同日汇总任务",
    })).toEqual({
      requiresConfirmation: true,
      canContinue: true,
      message: "原日期汇总 2026-07-24 的同日汇总任务已有认账结果，继续将先取消该范围的全部认账结果，再取消转移。是否继续？",
    });
  });

  it("blocks confirmation without permission or when results are locked or vouchered", () => {
    expect(deriveDetailOperationCancellationDecision({
      resultCount: 1,
      hasCancelPermission: false,
      hasLockedResult: false,
      hasGeneratedVoucher: false,
      operationLabel: "忽略",
      originalDate: "2026-07-24",
      scopeLabel: "该银行到账",
    }).canContinue).toBe(false);

    expect(deriveDetailOperationCancellationDecision({
      resultCount: 1,
      hasCancelPermission: true,
      hasLockedResult: true,
      hasGeneratedVoucher: false,
      operationLabel: "转移",
      originalDate: "2026-07-24",
      scopeLabel: "多日汇总匹配组",
    })).toMatchObject({
      requiresConfirmation: true,
      canContinue: false,
      message: "原日期汇总已有已锁定或已生成凭证的认账结果，请先取消凭证或锁定后再取消转移",
    });
  });

  it("blocks linked cancellation when any recognition result has archived details", () => {
    expect(deriveDetailOperationCancellationDecision({
      resultCount: 2,
      hasCancelPermission: true,
      hasLockedResult: false,
      hasGeneratedVoucher: false,
      hasArchivedDetails: true,
      operationLabel: "转移",
      originalDate: "2026-05-01",
      scopeLabel: "该银行到账",
    })).toEqual({
      requiresConfirmation: true,
      canContinue: false,
      message: "原日期汇总包含已归档订单明细，只能取消热区订单明细的认账，无法取消转移",
    });
  });
});

describe("hot-only recognition cancellation", () => {
  it("chunks a 219,693-row cancellation scope before SQL construction", () => {
    const detailIds = Array.from({ length: 219_693 }, (_, index) => index + 1);
    const chunks = chunkRecognitionCancellationDetailIds(detailIds);

    expect(chunks).toHaveLength(220);
    expect(chunks.every((chunk) => chunk.length <= 1000)).toBe(true);
    expect(chunks[0][0]).toBe(1);
    expect(chunks.at(-1)?.at(-1)).toBe(219_693);
  });

  it("detects an archived result anywhere in the cancellation scope", () => {
    expect(hasArchivedRecognitionDetails([
      row({ id: 1, hasArchivedDetails: false }),
      row({ id: 2, hasArchivedDetails: true }),
    ])).toBe(true);
    expect(hasArchivedRecognitionDetails([
      row({ id: 1, hasArchivedDetails: false }),
      row({ id: 2, hasArchivedDetails: 0 }),
    ])).toBe(false);
  });

  it("only exposes cancellation for recognition results that remain in the hot area", () => {
    expect(canCancelFlowRecognition({
      hasRecognition: true,
      hasArchivedDetails: false,
    })).toBe(true);
    expect(canCancelFlowRecognition({
      hasRecognition: true,
      hasArchivedDetails: true,
    })).toBe(false);
    expect(canCancelFlowRecognition({
      hasRecognition: false,
      hasArchivedDetails: false,
    })).toBe(false);
  });

  it("distinguishes deleted hot details from archived details", () => {
    expect(classifyRecognitionCancellationDetailCoverage({
      expectedDetailCount: 94,
      hotDetailCount: 0,
      hasArchivedDetails: false,
      hasCompletedArchiveRun: false,
    })).toEqual({
      status: "orphaned",
      missingDetailCount: 94,
    });
    expect(classifyRecognitionCancellationDetailCoverage({
      expectedDetailCount: 94,
      hotDetailCount: 0,
      hasArchivedDetails: false,
      hasCompletedArchiveRun: true,
    })).toEqual({
      status: "archived",
      missingDetailCount: 94,
    });
  });

  it("keeps complete hot detail coverage cancellable", () => {
    expect(classifyRecognitionCancellationDetailCoverage({
      expectedDetailCount: 94,
      hotDetailCount: 94,
      hasArchivedDetails: false,
      hasCompletedArchiveRun: true,
    })).toEqual({
      status: "complete",
      missingDetailCount: 0,
    });
  });

  it("retries derived-state refresh without turning a committed cancellation into a failure", async () => {
    let attempts = 0;
    const result = await retryCommittedRecognitionCancellationRefresh({
      refresh: async () => {
        attempts += 1;
        if (attempts < 3) throw new Error("temporary refresh failure");
      },
      maxAttempts: 3,
    });

    expect(result).toEqual({
      success: true,
      attempts: 3,
    });
  });

  it("reports exhausted refresh retries without throwing", async () => {
    const errors: number[] = [];
    const result = await retryCommittedRecognitionCancellationRefresh({
      refresh: async () => {
        throw new Error("persistent refresh failure");
      },
      maxAttempts: 2,
      onAttemptError: (_error, attempt) => errors.push(attempt),
    });

    expect(result.success).toBe(false);
    expect(result.attempts).toBe(2);
    expect(errors).toEqual([1, 2]);
  });
});
